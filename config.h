#pragma once

// ---------------------------------------------------------------------------
// ЗАПРЕЩЁННЫЕ / ОПАСНЫЕ GPIO НА ESP32-C6 (сверено с даташитом Espressif,
// таблица strapping pins + распиновка ESP32-C6-DevKitC-1 v1.2):
//
//   GPIO4  (MTMS) — strapping pin (boot config)      -> НЕ занимать
//   GPIO5  (MTDI) — strapping pin (boot config)      -> НЕ занимать
//   GPIO8         — strapping pin (boot mode)         -> НЕ занимать
//                    (на DevKitC-1 на этот же пин ещё и WS2812 RGB LED)
//   GPIO9         — strapping pin (boot mode, к нему подтянута кнопка BOOT) -> НЕ занимать
//   GPIO12        — USB_D-  (родной USB-Serial/JTAG)  -> НЕ занимать, если используешь USB
//   GPIO13        — USB_D+  (родной USB-Serial/JTAG)  -> НЕ занимать, если используешь USB
//   GPIO15        — strapping pin (JTAG select)        -> НЕ занимать
//
// Условно свободные (используются под консоль UART0, но на DevKitC-1
// с нативным USB это НЕ обязательно, свободны, если не шьёшь через
// внешний UART-мост):
//   GPIO16 (U0TXD), GPIO17 (U0RXD)
//
// Реально свободные GPIO под свою логику на DevKitC-1:
//   0, 1, 2, 3, 6, 7, 10, 11, (16, 17), 18, 19, 20, 21, 22, 23
//
// Ниже — выбор из этого списка, максимально далеко от USB/strapping/UART.
// ---------------------------------------------------------------------------

// Серво: ось PAN (азимут) и TILT (угол места). LEDC на C6 умеет висеть на
// любом свободном GPIO — жёстко закреплённых "servo-каналов" нет.
#define PIN_SERVO_PAN     18   // свободный GPIO, далеко от strapping/USB
#define PIN_SERVO_TILT    19   // свободный GPIO, далеко от strapping/USB

// Резерв под будущее расширение (кнопка калибровки, статусный светодиод и т.п.)
#define PIN_STATUS_LED    20   // опционально, не используется в коде v1
#define PIN_CAL_BUTTON    21   // опционально, не используется в коде v1

// ---------------------------------------------------------------------------
// LEDC (PWM) для серво.
// Arduino-ESP32 core 3.x API: ledcAttach(pin, freq, resolution_bits);
//                              ledcWrite(pin, duty);
// 50 Гц, 14 бит (16384 шагов) — стандартный рабочий режим для серво на C6,
// проверенная связка из официальных примеров core 3.x.
// ---------------------------------------------------------------------------
#define SERVO_PWM_FREQ_HZ     50
#define SERVO_PWM_RESOLUTION  14                    // 16384 шагов
#define SERVO_PWM_MAX_DUTY    ((1 << SERVO_PWM_RESOLUTION) - 1)
#define SERVO_PERIOD_US       (1000000UL / SERVO_PWM_FREQ_HZ)  // 20000 мкс

// Диапазон импульса серво в микросекундах. SG90/HG90/MG90S обычно указывают
// 500..2400, но реальный ход дешёвых 9g часто НЕ 0..180°, а урезан.
// Эти значения — стартовые заводские, их правит калибровка (сохраняется в NVS).
#define SERVO_PULSE_MIN_US_DEFAULT   500
#define SERVO_PULSE_MAX_US_DEFAULT   2400

// Программные концевики по УГЛУ (не по мкс). Заявка ТЗ: реальный ход дешёвых
// 9g часто ~10..170°, не 0..180. Отдельно урезаем рабочий сектор обзора —
// он должен быть уже, чем механический ход, с запасом на калибровочный люфт.
#define PAN_ANGLE_MIN_DEFAULT     15   // азимут, градусы
#define PAN_ANGLE_MAX_DEFAULT     165
#define TILT_ANGLE_MIN_DEFAULT    10   // угол места, градусы
#define TILT_ANGLE_MAX_DEFAULT    80

// Позиция парковки (безопасное положение при простое / полном Wi-Fi скане)
#define PARK_PAN_DEFAULT   90
#define PARK_TILT_DEFAULT  45

// ---------------------------------------------------------------------------
// Сетка сканирования.
// Диаграмма направленности 5-эл. Yagi (thing:6827189) по азимуту ~40°.
// Грубый шаг должен быть заметно меньше ширины лепестка, иначе пик
// проскакивается между соседними точками сетки. Берём с запасом.
// ---------------------------------------------------------------------------
#define COARSE_STEP_DEG_DEFAULT   12    // грубый растр, град (спека: 10-15, не грубее 12-15 для этой антенны)
#define FINE_STEP_DEG_DEFAULT      2    // точный растр вокруг пика
#define REFINE_STEP_DEG            1    // финальный координатный спуск
#define MAX_REFINE_ITERS           10   // ограничение числа итераций точного донаведения (защита от зацикливания)
#define TRACK_PERIOD_MS          1500   // период повторного опроса соседей в режиме непрерывного слежения

// Полуширина окна точного скана вокруг найденного грубого пика (градусы).
// Истинный пик лежит не дальше половины грубого шага от точки, где грубый
// растр его засёк (COARSE_STEP/2 = 6° при шаге 12°). Берём с запасом.
#define FINE_WINDOW_DEG           10

// Тайминги серво/измерений
#define SERVO_SETTLE_MS_DEFAULT     120   // успокоение серво после команды
#define BLE_DWELL_MS_COARSE       450     // окно измерения BLE, грубая сетка
#define BLE_DWELL_MS_FINE         250     // окно измерения BLE, точная сетка
#define WIFI_CHAN_SCAN_MS         180     // max_ms_per_chan для посканального Wi-Fi скана
#define WIFI_FULLSCAN_MS_PER_CHAN 260     // при полном скане 1..13 каналов (парковка)

// Фильтрация RSSI
#define RSSI_SAMPLE_MEDIAN_N        5     // окно медианного фильтра (число последних сэмплов)
#define RSSI_EMA_ALPHA_PERCENT     40     // вес нового сэмпла в EMA, % (0..100)
#define RSSI_FLOOR_DBM_DEFAULT    -95     // порог отсечки "слишком тихо", настраивается
#define RSSI_DEADBAND_DB            2     // не дёргать серво, если |ΔRSSI| меньше этого

// "Не измерено" в карте RSSI
#define RSSI_NOT_MEASURED  (-128)

// Максимальный диапазон карты (используется как размер статических массивов)
#define MAP_PAN_MAX_DEG   181   // индексы 0..180
#define MAP_TILT_MAX_DEG   91   // индексы 0..90

// ---------------------------------------------------------------------------
// Радио / веб.
// ---------------------------------------------------------------------------
#define SOFTAP_SSID       "C6-Tracker"
#define SOFTAP_PASSWORD   "trackerc6"     // >=8 символов, обязателен для WPA2; пусто -> открытая сеть
#define SOFTAP_CHANNEL    6                // фиксируем канал AP, чтобы не плавал при STA-сканах
                                             // (гипотеза "скан на чужом канале тихо проваливается"
                                             // проверена и ОТБРОШЕНА — см. README: реальная причина
                                             // несовпадения была в рандомизации BSSID точки доступа
                                             // на телефоне, канал тут ни при чём)
#define WEB_SERVER_PORT   80

// BLE
// ВАЖНО (найдено эмпирически на реальном железе ESP32-C6): window ДОЛЖЕН быть
// заметно меньше interval. При window == interval скан идёт с нулевым зазором
// (100% duty cycle) и на ESP32-C6 это душит сосуществование радио настолько,
// что SoftAP перестаёт отвечать на ассоциацию клиентов вообще (проверено:
// клиенты видят точку по маяку, но не могут подключиться, пока скан активен
// с нулевым зазором; с ~30% duty cycle — подключаются нормально). Держи
// window заметно (в разы) меньше interval, не выкручивай оба в максимум.
#define BLE_SCAN_INTERVAL_MS  160   // NimBLE setInterval (в единицах 0.625 мс переводится в коде)
#define BLE_SCAN_WINDOW_MS     48   // ~30% duty cycle — реальный зазор для Wi-Fi AP
#define BLE_ACTIVE_SCAN_DEFAULT false  // пассивный скан по умолчанию (меньше эфирного времени)
#define BLE_SEEN_LIST_MAX       24     // сколько устройств держим в списке "обнаружено"
#define BLE_SEEN_TIMEOUT_MS   20000    // через сколько мс устройство пропадает из списка, если не слышно

// Wi-Fi
#define WIFI_SEEN_LIST_MAX       32

// NVS (Preferences) namespace/ключи калибровки
#define NVS_NAMESPACE   "trkcal"

// Serial
#define SERIAL_BAUD    115200
